            $(document).on('click', '.jshndle-contact-form-submit', function (event) {
                event.preventDefault();

                let $this = $(this);
                $this.html('<i class="fa-solid fa-loader fa-spin"></i>');

                let isValid = true;

                let firstName = $('#first_name');
                let lastName = $('#last_name');
                let email = $('#email');
                let phone = $('#phone_number');
                let message = $('#message');
                let terms = $('#terms');

                $('.text-invalid, .file-invalid, .check-invalid').removeClass('text-invalid file-invalid check-invalid');

                if (!firstName.val()) {
                    firstName.addClass('text-invalid'); isValid = false;
                }
                if (!lastName.val()) {
                    lastName.addClass('text-invalid'); isValid = false;
                }
                if (!email.val() || !/^\S+@\S+\.\S+$/.test(email.val())) {
                    email.addClass('text-invalid'); isValid = false;
                }
                if (!phone.val()) {
                    phone.addClass('text-invalid'); isValid = false;
                }
                if (!message.val()) {
                    message.addClass('text-invalid'); isValid = false;
                }

                if (!terms.is(':checked')) {
                    terms.closest('label').addClass('check-invalid'); isValid = false;
                }

                setTimeout(() => {
                    $('.text-invalid, .file-invalid, .check-invalid').removeClass('text-invalid file-invalid check-invalid');
                }, 5000);

                if (!isValid) {
                    $this.html('🔄 Retry!');

                    setTimeout(() => {
                        $this.html('Apply');
                    }, 2000);
                    return;
                }

                let formData = new FormData();
                formData.append('first_name', firstName.val());
                formData.append('last_name', lastName.val());
                formData.append('email', email.val());
                formData.append('phone_number', phone.val());
                formData.append('message', message.val());
                formData.append("_token", "{{ csrf_token() }}");

                $.ajax({
                    type: "POST",
                    url: "{{ route('contactSubmit') }}",
                    data: formData,
                    processData: false,
                    contentType: false,
                    success: function (response) {
                        if (response['success']) {
                            $('.jshndle-job-form')[0].reset();
                            $this.html('👍 Thank You!');

                            setTimeout(() => {
                                $this.html('— Submit');
                            }, 2000);
                        } else {
                            $this.html('🔄 Retry!');

                            setTimeout(() => {
                                $this.html('— Submit');
                            }, 2000);
                        }
                    }
                });
            });
